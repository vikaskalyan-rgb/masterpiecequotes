create index if not exists ix_terms_quote on term_items (quote_id);

-- ---------- snapshots: exactly what was shared with the customer ----------
create table if not exists quote_snapshots (
    id            bigint generated by default as identity primary key,
    quote_id      bigint         not null references quotes (id) on delete cascade,
    created_at    timestamp(6) with time zone not null,
    content_hash  varchar(64)    not null,
    rounded_total numeric(12, 2) not null,
    payload       text           not null
);
create index if not exists ix_snapshots_quote on quote_snapshots (quote_id, created_at desc);

-- ---------- business profile (was hardcoded in the PDF template) ----------
