alter table quotes add column if not exists total_overridden  boolean not null default false;
alter table quotes add column if not exists valid_until       date;
alter table quotes add column if not exists client_request_id varchar(64);
alter table quotes add column if not exists first_sent_at     timestamp(6) with time zone;
alter table quotes add column if not exists deleted_at        timestamp(6) with time zone;

-- Number existing quotes in the order they were created, then continue from there.
create sequence if not exists quote_number_seq start with 1;

with numbered as (
    select id, row_number() over (order by created_at, id) as n
    from quotes
    where quote_number is null
)
update quotes q
set quote_number = numbered.n + coalesce((select max(quote_number) from quotes), 0)
from numbered
where q.id = numbered.id;

select setval('quote_number_seq', coalesce((select max(quote_number) from quotes), 0) + 1, false);

alter table quotes alter column quote_number set default nextval('quote_number_seq');
alter table quotes alter column quote_number set not null;
create unique index if not exists ux_quotes_quote_number on quotes (quote_number);
create unique index if not exists ux_quotes_client_request_id on quotes (client_request_id) where client_request_id is not null;
create index if not exists ix_quotes_updated_at on quotes (updated_at desc);

-- Phone numbers: digits only, with India's country code added to bare 10-digit numbers, so
-- search and WhatsApp links work regardless of how the number was originally typed.
with digits as (
    select id, regexp_replace(customer_phone, '\D', '', 'g') as d from quotes
), normalized as (
    select id,
           case
               when length(d) = 10 then '91' || d
               when length(d) = 11 and d like '0%' then '91' || substr(d, 2)
               else d
           end as phone
    from digits
)
update quotes q
set customer_phone = normalized.phone
from normalized
where q.id = normalized.id
  and normalized.phone <> ''
  and q.customer_phone is distinct from normalized.phone;

-- Existing totals: the old app auto-rounded to the nearest 1,000. A saved total equal to
-- that value was automatic; anything else was typed by hand and must be preserved as-is.
update quotes
set total_overridden = (rounded_total is distinct from round(coalesce(subtotal, 0) / 1000) * 1000);

-- ---------- items: dimensions were stored twice ----------
-- Descriptions like "Wardrobe Framed (7X4)" duplicated the length/width columns. Strip the
-- suffix only where it matches the stored columns exactly and something is left over.
update items i
set description = trim(regexp_replace(i.description, '\s*\(\s*[0-9.]+\s*[xX]\s*[0-9.]+\s*\)\s*$', ''))
where i.unit = 'SQFT'
  and i.length is not null
  and i.width is not null
  and i.description ~ '\(\s*[0-9]+(\.[0-9]+)?\s*[xX]\s*[0-9]+(\.[0-9]+)?\s*\)\s*$'
  and (regexp_match(i.description, '\(\s*([0-9]+(?:\.[0-9]+)?)\s*[xX]\s*([0-9]+(?:\.[0-9]+)?)\s*\)\s*$'))[1]::numeric = i.length
  and (regexp_match(i.description, '\(\s*([0-9]+(?:\.[0-9]+)?)\s*[xX]\s*([0-9]+(?:\.[0-9]+)?)\s*\)\s*$'))[2]::numeric = i.width
  and trim(regexp_replace(i.description, '\s*\(\s*[0-9.]+\s*[xX]\s*[0-9.]+\s*\)\s*$', '')) <> '';

create index if not exists ix_items_room on items (room_id);
create index if not exists ix_rooms_quote on rooms (quote_id);
