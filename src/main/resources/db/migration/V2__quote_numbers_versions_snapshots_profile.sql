    id              smallint primary key default 1 check (id = 1),
    name            varchar(120) not null,
    tagline         varchar(200),
    address         varchar(500) not null,
    phone_primary   varchar(30)  not null,
    phone_secondary varchar(30),
    email           varchar(120),
    gstin           varchar(15),
    signatory       varchar(120) not null,
