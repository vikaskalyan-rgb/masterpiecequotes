-- V1: the schema the app had before migrations were introduced (previously created by
-- Hibernate's ddl-auto=update). On the existing production database Flyway records this
-- version as the baseline and skips it; on a fresh database it creates the original tables,
-- so every environment reaches V2 from the same starting point.

create table if not exists quotes (
    id                      bigint generated by default as identity primary key,
    customer_name           varchar(255)   not null,
    customer_phone          varchar(255)   not null,
    customer_address        text,
    quote_date              date           not null,
    status                  varchar(255)   not null check (status in ('DRAFT', 'SENT', 'ACCEPTED', 'REJECTED')),
    subtotal                numeric(12, 2),
    rounded_total           numeric(12, 2),
    accessories_description varchar(255),
    accessories_amount      numeric(12, 2),
    created_at              timestamp(6) with time zone not null,
    updated_at              timestamp(6) with time zone not null
);

create table if not exists rooms (
    id         bigint generated by default as identity primary key,
    quote_id   bigint       not null references quotes (id),
    name       varchar(255) not null,
    sort_order integer      not null
);

create table if not exists items (
    id          bigint generated by default as identity primary key,
    room_id     bigint         not null references rooms (id),
    description varchar(255)   not null,
    length      numeric(10, 2),
    width       numeric(10, 2),
    quantity    numeric(10, 2) not null,
    unit        varchar(255)   not null check (unit in ('SQFT', 'NOS')),
    rate        numeric(10, 2) not null,
    amount      numeric(12, 2) not null,
    sort_order  integer        not null
);

create table if not exists material_spec_items (
    id         bigint generated by default as identity primary key,
    quote_id   bigint       not null references quotes (id),
    item_label varchar(255) not null,
    detail     varchar(255),
    brand      varchar(255),
    sort_order integer      not null
);

create table if not exists term_items (
    id         bigint generated by default as identity primary key,
    quote_id   bigint  not null references quotes (id),
    text       text    not null,
    sort_order integer not null
);

create table if not exists default_material_spec_items (
    id         bigint generated by default as identity primary key,
    item_label varchar(255) not null,
    detail     varchar(255),
    brand      varchar(255),
    sort_order integer      not null
);

create table if not exists default_term_items (
    id         bigint generated by default as identity primary key,
    text       text    not null,
    sort_order integer not null
);
